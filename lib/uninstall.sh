#!/usr/bin/env bash
# Slice 5: uninstall. Restores the user to their pre-install state rather than
# just deleting files: the previous speech-dispatcher config comes back and
# espeak-ng goes back to being the default voice.

# Read a key from the state file written at install time.
state_get() {
    [ -f "$SPD_STATE" ] || return 1
    sed -n "s/^$1=//p" "$SPD_STATE" | head -1
}

# Remove a voice, but only one this script installed.
remove_voice() {
    local key=$1 dir="$VOICE_STORE/$1"
    [ -d "$dir" ] || return 0
    if [ -f "$dir/.installed-by-firefox-piper" ]; then
        rm -rf "$dir"
        ok "removed voice $key"
    else
        warn "keeping $dir: not installed by this script"
    fi
}

remove_piper_runtime() {
    if [ -d "$PIPER_HOME" ] || [ -f "$PIPER_BIN" ]; then
        rm -rf "$PIPER_HOME"
        rm -f "$PIPER_BIN" "$PIPER_SPEAK"
        ok "removed Piper runtime"
    fi
}

# Put the original speech-dispatcher config back if we saved one.
restore_speechd_config() {
    if [ -f "$SPD_BACKUP" ]; then
        cp -p "$SPD_BACKUP" "$SPD_CONF"
        rm -f "$SPD_BACKUP"
        ok "restored your previous speechd.conf"
    elif [ -f "$SPD_CONF" ] && grep -q "Generated by firefox-piper" "$SPD_CONF"; then
        # Nothing was backed up, so the whole file is ours to remove.
        rm -f "$SPD_CONF"
        ok "removed generated speechd.conf (speech-dispatcher falls back to system defaults)"
    else
        warn "leaving $SPD_CONF in place: not generated by this script"
    fi
}

uninstall_all() {
    local keep_voices=no purge_packages=no voice_key

    # Flags may arrive either before or after the subcommand.
    while [ $# -gt 0 ]; do
        case "$1" in
            --keep-voices) keep_voices=yes; shift ;;
            --purge-packages) purge_packages=yes; shift ;;
            *) die "unknown option for uninstall: $1" ;;
        esac
    done

    info "uninstalling Piper from speech-dispatcher"

    voice_key=$(state_get voice) || voice_key=""

    # 1. Restore speech-dispatcher first, so narration works again immediately.
    restore_speechd_config
    rm -f "$SPD_PIPER_CONF" "$SPD_STATE"
    rmdir "$SPD_MODULES_DIR" 2>/dev/null || true
    ok "removed Piper module config"

    # 2. Voices.
    if [ "$keep_voices" = "no" ] && [ -d "$VOICE_STORE" ]; then
        local dir
        for dir in "$VOICE_STORE"/*/; do
            [ -d "$dir" ] || continue
            remove_voice "$(basename "$dir")"
        done
        rmdir "$VOICE_STORE" 2>/dev/null || true
    else
        warn "keeping downloaded voices in $VOICE_STORE"
    fi

    # 3. The runtime and wrapper.
    remove_piper_runtime

    # 4. Optionally the packages we installed. espeak-ng is deliberately left
    #    alone so the user keeps a working speech engine.
    if [ "$purge_packages" = "yes" ]; then
        info "removing apt packages this script installed"
        sudo_ apt-get remove -y speech-dispatcher speech-dispatcher-espeak-ng \
            || warn "apt-get remove reported an error; check installed packages manually"
    else
        dim "packages left in place (speech-dispatcher, espeak-ng)"
        dim "re-run with --purge-packages to remove them"
    fi

    restart_speech_dispatcher

    log ""
    ok "uninstalled"
    dim "espeak-ng remains the default voice, as it was before."
    log ""
}