#!/usr/bin/env bash
# Slice 1: system dependencies and the Piper runtime itself.
#
# Debian 13 ships no `piper-tts` package, so the runtime comes from the upstream
# GitHub release archive (verified: piper_linux_x86_64.tar.gz, tag 2023.11.14-2).
# The archive bundles its own libonnxruntime, libespeak-ng and espeak-ng-data,
# including the `bg` dictionary Bulgarian voices need, so nothing else is required.

PIPER_RELEASE="2023.11.14-2"
PIPER_ARCHIVE_URL="https://github.com/rhasspy/piper/releases/download/${PIPER_RELEASE}/piper_linux_x86_64.tar.gz"

# Debian packages we depend on. speech-dispatcher and espeak-ng are kept as the
# espeak fallback rather than replaced.
REQUIRED_PACKAGES=(
    "speech-dispatcher"
    "speech-dispatcher-espeak-ng"
    "curl"
    "tar"
)

# Resolve the platform-specific archive name; only x86_64 is published for this tag.
piper_archive_url() {
    local arch
    arch=$(uname -m)
    case "$arch" in
        x86_64|amd64) printf '%s\n' "$PIPER_ARCHIVE_URL" ;;
        aarch64|arm64)
            die "No prebuilt Piper binary for $arch. Install Piper manually and re-run with --piper-bin."
            ;;
        *) die "Unsupported architecture: $arch" ;;
    esac
}

missing_packages() {
    local pkg
    for pkg in "${REQUIRED_PACKAGES[@]}"; do
        dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null | grep -q "ok installed" || printf '%s\n' "$pkg"
    done
}

install_dependencies() {
    local missing
    missing=$(missing_packages | tr '\n' ' ')
    missing=${missing% }
    if [ -z "$missing" ]; then
        ok "system dependencies present"
        return 0
    fi

    info "installing system dependencies: $missing"
    info "this needs root (apt) access"
    sudo_ apt-get update -qq || die "apt-get update failed"
    # shellcheck disable=SC2086
    sudo_ apt-get install -y --no-install-recommends $missing \
        || die "apt-get install failed for: $missing"
    ok "system dependencies installed"
}

# espeak-ng stays installed and reachable so `--uninstall` can restore it as the
# default voice. We only assert it is present, never remove it.
require_espeak_fallback() {
    dpkg-query -W -f='${Status}' speech-dispatcher-espeak-ng 2>/dev/null | grep -q "ok installed" \
        || warn "speech-dispatcher-espeak-ng is missing; uninstall will not be able to restore it automatically."
}

install_piper_runtime() {
    if piper_available; then
        ok "piper runtime already installed ($(piper_version))"
        return 0
    fi

    local url tmp
    url=$(piper_archive_url)
    mkdir -p "$PIPER_HOME"
    tmp=$(mktemp -d)
    # shellcheck disable=SC2064
    trap "rm -rf '$tmp'" RETURN

    info "downloading Piper ${PIPER_RELEASE}"
    curl -fsSL --retry 3 --connect-timeout 20 -o "$tmp/piper.tar.gz" "$url" \
        || die "failed to download Piper from $url"

    info "extracting Piper runtime"
    tar -xzf "$tmp/piper.tar.gz" -C "$tmp" || die "failed to extract Piper archive"
    [ -x "$tmp/piper/piper" ] || die "Piper binary missing from archive"

    rm -rf "$PIPER_HOME/bin"
    mv "$tmp/piper" "$PIPER_HOME/bin"

    # The wrapper sets LD_LIBRARY_PATH so the bundled shared libraries resolve.
    cat > "$PIPER_BIN" <<WRAPPER
#!/usr/bin/env bash
# Generated by firefox-piper. Runs the bundled Piper runtime.
export LD_LIBRARY_PATH="$PIPER_HOME/bin\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec "$PIPER_HOME/bin/piper" "\$@"
WRAPPER
    chmod +x "$PIPER_BIN"

    piper_available || die "Piper installed but not runnable at $PIPER_BIN"
    ok "piper runtime installed ($PIPER_BIN)"
}

piper_available() { [ -x "$PIPER_BIN" ] && "$PIPER_BIN" --version >/dev/null 2>&1; }

piper_version() {
    "$PIPER_BIN" --version 2>&1 | head -1 | tr -d '\r' || true
}